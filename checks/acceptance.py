def канон(значение):
    """Одинаковое представление для словарей, в каком бы порядке ни шли ключи."""
    if isinstance(значение, dict):
        return tuple(sorted((str(к), канон(з)) for к, з in значение.items()))
    if isinstance(значение, (list, tuple)):
        return [канон(з) for з in значение]
    return значение


def отпечаток(вызов, значение):
    return hashlib.sha256(f"d11-t9|{вызов}|{канон(значение)!r}".encode("utf-8")).hexdigest()


def ожидать_скрыто(вызов, получено):
    """Сравнить результат с ожиданием, которое известно только по контрольной сумме."""
    хэши = ХЭШИ
    if ЗАПИСЬ_ХЭШЕЙ is not None:
        ЗАПИСЬ_ХЭШЕЙ[вызов] = отпечаток(вызов, получено)
        return
    if хэши.get(вызов) == отпечаток(вызов, получено):
        return
    показано = repr(получено)
    if len(показано) > 300:
        показано = показано[:300] + " …"
    raise НеСходится(f"{вызов}\n      получено:  {показано}"
                     f"\n      правильный ответ в этом пункте закрыт")


