def данные_целы(корень):
    испорчены = []
    for имя, сумма in КОНТРОЛЬНЫЕ_СУММЫ.items():
        путь = корень / имя
        if not путь.exists():
            испорчены.append(f"{имя} (нет файла)")
            continue
        содержимое = путь.read_bytes().replace(b"\r\n", b"\n")
        if hashlib.sha256(содержимое).hexdigest() != сумма:
            испорчены.append(f"{имя} (изменён)")
    return испорчены


def сторонние_импорты(корень):
    """Найти в src/*.py импорты не из стандартной библиотеки."""
    import ast
    import importlib.util as iu
    стандартные = getattr(sys, "stdlib_module_names", None)
    путь_stdlib = str(Path(sysconfig.get_paths()["stdlib"]).resolve())

    def из_stdlib(имя):
        if стандартные is not None:
            return имя in стандартные
        spec = iu.find_spec(имя)
        if spec is None:
            return False
        if spec.origin in ("built-in", "frozen"):
            return True
        if not spec.origin:
            return False
        путь = str(Path(spec.origin).resolve())
        return путь.startswith(путь_stdlib) and "site-packages" not in путь

    свои = {п.stem for п in (корень / "src").glob("*.py")}
    найдено = []
    for файл in sorted((корень / "src").glob("*.py")):
        try:
            дерево = ast.parse(файл.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for узел in ast.walk(дерево):
            имена = []
            if isinstance(узел, ast.Import):
                имена = [а.name for а in узел.names]
            elif isinstance(узел, ast.ImportFrom) and узел.module and узел.level == 0:
                имена = [узел.module]
            for имя in имена:
                верх = имя.split(".")[0]
                if верх in свои or верх == "__future__" or из_stdlib(верх):
                    continue
                найдено.append(f"{файл.name}: {имя}")
    return найдено


def с_ограничением_времени(функция, *аргументы):
    if not hasattr(signal, "SIGALRM"):
        return функция(*аргументы)

    def стоп(*_):
        raise Долго()
    прежний = signal.signal(signal.SIGALRM, стоп)
    signal.alarm(ЛИМИТ_СЕКУНД)
    try:
        return функция(*аргументы)
    finally:
        signal.alarm(0)
        signal.signal(signal.SIGALRM, прежний)


