def правильные_предложения_чатов():
    """Правильные предложения корпуса чатов из checks/chats_2000_sentences.dat или None.
    Файл сверяется с той же контрольной суммой, что и ответ read_sentences, поэтому подменить его нельзя."""
    if not _правильные_предложения:
        предложения = None
        import zlib
        try:
            import gzip
            текст = gzip.decompress(ФАЙЛ_ПРЕДЛОЖЕНИЙ.read_bytes()).decode("utf-8")
            предложения = [строка.split(" ") for строка in текст.split("\n")]
            if ХЭШИ.get(ПРЕДЛОЖЕНИЯ_ЧАТОВ) != отпечаток(ПРЕДЛОЖЕНИЯ_ЧАТОВ, предложения):
                предложения = None
        except (OSError, ValueError, EOFError, zlib.error):
            предложения = None
        _правильные_предложения.append(предложения)
    return _правильные_предложения[0]


