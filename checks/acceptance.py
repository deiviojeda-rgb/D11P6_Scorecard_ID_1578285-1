def ожидать(вызов, получено, ожидалось):
    """Сравнить результат с ожиданием и объяснить расхождение."""
    if получено == ожидалось:
        return
    подробно = ""
    if isinstance(получено, list) and isinstance(ожидалось, list) and len(ожидалось) > 5:
        for i, (п, о) in enumerate(zip(получено, ожидалось)):
            if п != о:
                подробно = f"\n      первое расхождение в элементе [{i}]: ожидалось {о!r}, получено {п!r}"
                break
        else:
            подробно = f"\n      длина: ожидалось {len(ожидалось)}, получено {len(получено)}"
        raise НеСходится(f"{вызов}{подробно}")
    if isinstance(получено, dict) and isinstance(ожидалось, dict) and len(ожидалось) > 5:
        for ключ in sorted(set(получено) | set(ожидалось), key=str):
            if получено.get(ключ, "нет такого ключа") != ожидалось.get(ключ, "нет такого ключа"):
                raise НеСходится(
                    f"{вызов}\n      первое расхождение по ключу {ключ!r}:"
                    f"\n      ожидалось: {ожидалось.get(ключ, 'нет такого ключа')!r}"
                    f"\n      получено:  {получено.get(ключ, 'нет такого ключа')!r}")
    raise НеСходится(f"{вызов}\n      ожидалось: {ожидалось!r}\n      получено:  {получено!r}")


