def эталон_ngrams(предложения, n):
    """Подсчёт n-грамм самой проверки: так строятся учебные модели для заданий 2–6."""
    модель = {}
    for предложение in предложения:
        токены = ["<s>"] * (n - 1) + list(предложение) + ["</s>"]
        for i in range(n - 1, len(токены)):
            счётчики = модель.setdefault(" ".join(токены[i - n + 1:i]), {})
            счётчики[токены[i]] = счётчики.get(токены[i], 0) + 1
    return модель


