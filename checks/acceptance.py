def правильная_normalize(word):
    return word.lower().replace("ё", "е")


def правильная_top_k(counts, k):
    return [слово for слово, _ in sorted(counts.items(), key=lambda пара: (-пара[1], пара[0]))[:k]]


def правильная_count_words(sentences):
    return {слово: число for слово, число in эталон_ngrams(sentences, 1).get("", {}).items() if слово != "</s>"}


def правильная_count_pairs(sentences):
    return эталон_ngrams(sentences, 2)


def правильная_count_ngrams(sentences, n):
    return эталон_ngrams(sentences, n)


def правильная_build_model(sentences, max_n):
    return {уровень: эталон_ngrams(sentences, уровень) for уровень in range(1, max_n + 1)}


def правильная_context_for(history, n):
    return " ".join((["<s>"] * (n - 1) + list(history))[-(n - 1):]) if n > 1 else ""


ПРАВИЛЬНЫЕ = {
    "normalize": правильная_normalize, "top_k": правильная_top_k, "count_words": правильная_count_words,
    "count_pairs": правильная_count_pairs, "count_ngrams": правильная_count_ngrams,
    "build_model": правильная_build_model, "context_for": правильная_context_for,
}


class Подмена:
    """Временно подставить в модуль участника правильные версии функций."""

    def __init__(self, t9, имена):
        self.t9, self.имена, self.было = t9, list(имена), {}

    def __enter__(self):
        for имя in self.имена:
            self.было[имя] = getattr(self.t9, имя, None)
            setattr(self.t9, имя, ПРАВИЛЬНЫЕ[имя])

    def __exit__(self, *_):
        for имя, функция in self.было.items():
            if функция is None:
                delattr(self.t9, имя)
            else:
                setattr(self.t9, имя, функция)


def выполнить(функция, t9, д):
    """Выполнить пункт. Вернуть (вид, текст, ненаписанная функция или None).
    Вид — «+», «·» (не написано), «-» или «долго»."""
    try:
        с_ограничением_времени(функция, t9, д)
    except NotImplementedError as ошибка:
        кадры = [к for к in traceback.extract_tb(ошибка.__traceback__) if к.filename.endswith("t9.py")]
        return "·", f"ещё не написано ({ошибка})", (кадры[-1].name if кадры else None)
    except НеСходится as ошибка:
        return "-", f"не сходится\n      {ошибка}", None
    except Долго:
        return "долго", f"дольше {ЛИМИТ_СЕКУНД} с — прервано", None
    except (Exception, SystemExit) as ошибка:
        return "-", f"ошибка {type(ошибка).__name__}: {ошибка}{место_ошибки(ошибка)}", None
    return "+", "", None


def перечислить(части):
    return части[0] if len(части) == 1 else ", ".join(части[:-1]) + " и " + части[-1]


def прямые_вызовы(функция):
    """Функции t9, которые пункт вызывает сам. Остальные функции участника пункт задействует косвенно."""
    имена, коды = set(), [функция.__code__]
    while коды:
        код = коды.pop()
        имена.update(код.co_names)
        коды.extend(к for к in код.co_consts if hasattr(к, "co_names"))
    return имена & set(ЗАДАНИЕ_ФУНКЦИИ)


ПРЯМЫЕ = [прямые_вызовы(функция) for _, _, функция in ПРОВЕРКИ]


class Разбор:
    """Ищет причину расхождения в другой функции участника и помнит результаты пунктов."""

    def __init__(self, t9, д, активен):
        self.t9, self.д, self.активен = t9, д, активен
        self.итоги = {}       # номер пункта в ПРОВЕРКИ -> (сошёлся ли, какая функция ещё не написана)
        self.подмены = {}     # набор подменённых функций -> свои данные для повторов

    def собственные(self, имя):
        """Итоги пунктов этого запуска, которые вызывают функцию сами."""
        for номер, (_, _, функция) in enumerate(ПРОВЕРКИ):
            if имя not in ПРЯМЫЕ[номер] or not self.активен(номер):
                continue
            if номер not in self.итоги:
                вид, _, ненаписанная = выполнить(функция, self.t9, self.д)
                self.итоги[номер] = (вид == "+", ненаписанная)
            yield self.итоги[номер]

    def свои_пункты_не_сходятся(self, имя):
        return any(not сошёлся for сошёлся, _ in self.собственные(имя))

    def не_написана(self, имя):
        return any(ненаписанная == имя for _, ненаписанная in self.собственные(имя))

    def сходится_с(self, номер, имена, предложения=None):
        """Сходится ли пункт с правильными версиями функций имена и, если даны, с правильными предложениями чатов."""
        ключ = (frozenset(имена), предложения is not None)
        if ключ not in self.подмены:
            self.подмены[ключ] = Данные(self.t9, self.д.корень, предложения)
        with Подмена(self.t9, имена):
            return выполнить(ПРОВЕРКИ[номер][2], self.t9, self.подмены[ключ])[0] == "+"

    def причина(self, номер, взяты_чаты):
        """(исключить ли пункт из оценки, пояснение) или None, если причина не найдена."""
        задание = ПРОВЕРКИ[номер][0]
        прямые = ПРЯМЫЕ[номер]
        правильные = None      # правильные предложения чатов, если у участника они неправильные
        начало = ""
        if задание > 1 and взяты_чаты and "read_sentences" not in прямые:
            верны, что_не_так = self.д.чаты_верны()
            if not верны:
                начало = f"предложения корпуса чатов из read_sentences (задание 1) {что_не_так}"
                правильные = правильные_предложения_чатов()
                if правильные is None:
                    return False, (f"{начало}, а правильных предложений для повтора нет: файл "
                                   f"checks/chats_2000_sentences.dat отсутствует или изменён. Пункт учитывается")
                if self.сходится_с(номер, [], правильные):
                    return True, (f"{начало}; на правильных предложениях пункт сходится, "
                                  f"ошибка учтена в пунктах задания 1")
        кандидаты = [имя for имя in ПРАВИЛЬНЫЕ if имя not in прямые and ЗАДАНИЕ_ФУНКЦИИ[имя] <= задание]
        if not кандидаты or not self.сходится_с(номер, кандидаты, правильные):
            if правильные is not None:
                return False, f"{начало}, но и на правильных предложениях пункт не сходится, поэтому учитывается"
            return None
        причины = list(кандидаты)
        for имя in reversed(кандидаты):    # оставить только подмены, без которых пункт снова не сходится
            if len(причины) > 1 and self.сходится_с(номер, [и for и in причины if и != имя], правильные):
                причины.remove(имя)
        названия = перечислить([f"{имя} (задание {ЗАДАНИЕ_ФУНКЦИИ[имя]})" for имя in причины])
        где = "на правильных предложениях корпуса чатов и " if правильные is not None else ""
        сошёлся = f"{где}с правильн{'ой' if len(причины) == 1 else 'ыми'} {названия} пункт сходится"
        if начало:
            сошёлся = f"{начало}; {сошёлся}"
        ненаписанные = [имя for имя in причины if ЗАДАНИЕ_ФУНКЦИИ[имя] == задание and self.не_написана(имя)]
        if ненаписанные:
            return False, (f"{сошёлся}, но {перечислить(ненаписанные)} ещё не написан"
                           f"{'а' if len(ненаписанные) == 1 else 'ы'}. Это невыполненная часть "
                           f"{чьё(задание)}, поэтому пункт учитывается")
        без_учёта = [имя for имя in причины if not self.свои_пункты_не_сходятся(имя)]
        if без_учёта:
            return False, (f"{сошёлся}, но собственные пункты {перечислить(без_учёта)} сходятся, "
                           f"поэтому пункт учитывается здесь")
        return True, f"{сошёлся}; ошибка учтена в собственных пунктах {перечислить(причины)}"


def чьё(задание):
    return f"задания {задание}" if задание in ОСНОВНЫЕ else f"бонуса {задание}"


ПОЯСНЕНИЕ = """
«Для оценки» — пункты задания без тех, что не сошлись из-за ошибки в другой функции.
Причину проверка подтверждает сама. Она повторяет пункт с правильной версией функции,
которую пункт вызывает не напрямую, и пункт сходится. Если пункт получил неправильные
предложения корпуса чатов, она повторяет его на правильных. Исключается пункт, только если ошибка уже учтена
в собственных пунктах той функции, — так каждая ошибка снижает оценку один раз.
Ненаписанная функция того же задания пункт не исключает: это невыполненная часть задания.
Такие пункты отмечены строкой «в оценку не идёт». По «для оценки» ставятся баллы."""


